// Schema for both engines. Timestamps are stored as 'YYYY-MM-DD HH:MM:SS' (UTC) strings
// written by the app, so both engines return identical values.

export function schemaStatements(dialect) {
  const my = dialect === 'mysql';
  const T = {
    id: my ? 'INT AUTO_INCREMENT PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT',
    int: my ? 'INT' : 'INTEGER',
    num: 'DOUBLE',
    str: (n) => `VARCHAR(${n})`,
    text: 'TEXT',
    big: my ? 'MEDIUMTEXT' : 'TEXT',
    ts: my ? 'DATETIME' : 'TEXT',
    date: my ? 'DATE' : 'TEXT',
  };
  const tail = my ? ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci' : '';
  const table = (name, body) => `CREATE TABLE IF NOT EXISTS ${name} (\n  ${body.join(',\n  ')}\n)${tail}`;
  const index = (name, tbl, cols) => (my ? `CREATE INDEX ${name} ON ${tbl} (${cols})` : `CREATE INDEX IF NOT EXISTS ${name} ON ${tbl} (${cols})`);

  return [
    table('users', [
      `id ${T.id}`,
      `email ${T.str(190)} NOT NULL UNIQUE`,
      `name ${T.str(120)} NOT NULL`,
      `password_hash ${T.str(255)} NOT NULL`,
      `role ${T.str(20)} NOT NULL DEFAULT 'user'`,
      `monthly_budget ${T.num} NULL`,
      `home_region ${T.str(40)} NULL`,
      `created_at ${T.ts} NOT NULL`,
    ]),
    table('sessions', [
      `token ${T.str(64)} NOT NULL PRIMARY KEY`,
      `user_id ${T.int} NOT NULL`,
      `created_at ${T.ts} NOT NULL`,
      `expires_at ${T.ts} NOT NULL`,
    ]),
    table('vehicle_presets', [
      `id ${T.id}`,
      `slug ${T.str(60)} NOT NULL UNIQUE`,
      `name ${T.str(120)} NOT NULL`,
      `category ${T.str(30)} NOT NULL`,
      `fuel_type ${T.str(20)} NOT NULL`,
      `product ${T.str(20)} NOT NULL`,
      `kmpl_city ${T.num} NOT NULL`,
      `kmpl_highway ${T.num} NOT NULL`,
      `mass_kg ${T.num} NOT NULL`,
      `engine_cc ${T.int} NULL`,
      `seats ${T.int} NULL`,
      `notes ${T.str(255)} NULL`,
    ]),
    table('user_vehicles', [
      `id ${T.id}`,
      `user_id ${T.int} NOT NULL`,
      `name ${T.str(120)} NOT NULL`,
      `preset_slug ${T.str(60)} NULL`,
      `category ${T.str(30)} NOT NULL`,
      `fuel_type ${T.str(20)} NOT NULL`,
      `product ${T.str(20)} NOT NULL`,
      `kmpl ${T.num} NOT NULL`,
      `mass_kg ${T.num} NULL`,
      `engine_cc ${T.int} NULL`,
      `tank_liters ${T.num} NULL`,
      `is_default ${T.int} NOT NULL DEFAULT 0`,
      `created_at ${T.ts} NOT NULL`,
    ]),
    table('fuel_logs', [
      `id ${T.id}`,
      `user_id ${T.int} NOT NULL`,
      `vehicle_id ${T.int} NULL`,
      `filled_on ${T.date} NOT NULL`,
      `odometer_km ${T.num} NULL`,
      `liters ${T.num} NOT NULL`,
      `price_per_liter ${T.num} NOT NULL`,
      `total_cost ${T.num} NOT NULL`,
      `full_tank ${T.int} NOT NULL DEFAULT 1`,
      `product ${T.str(20)} NULL`,
      `station_name ${T.str(160)} NULL`,
      `notes ${T.str(255)} NULL`,
      `created_at ${T.ts} NOT NULL`,
    ]),
    table('saved_trips', [
      `id ${T.id}`,
      `user_id ${T.int} NOT NULL`,
      `name ${T.str(160)} NOT NULL`,
      `origin_label ${T.str(255)} NULL`,
      `destination_label ${T.str(255)} NULL`,
      `distance_km ${T.num} NULL`,
      `cost_php ${T.num} NULL`,
      `payload ${T.text} NOT NULL`,
      `created_at ${T.ts} NOT NULL`,
    ]),
    // Official DOE prices. area = city/province or 'ALL'; brand = company or 'ALL'.
    table('fuel_prices', [
      `id ${T.id}`,
      `region ${T.str(40)} NOT NULL`,
      `area ${T.str(80)} NOT NULL`,
      `brand ${T.str(40)} NOT NULL`,
      `product ${T.str(20)} NOT NULL`,
      `price_min ${T.num} NULL`,
      `price_max ${T.num} NULL`,
      `price_common ${T.num} NULL`,
      `common_is_estimate ${T.int} NOT NULL DEFAULT 0`,
      `week_start ${T.date} NOT NULL`,
      `week_end ${T.date} NULL`,
      `source ${T.str(30)} NOT NULL`,
      `source_url ${T.text} NULL`,
      `fetched_at ${T.ts} NOT NULL`,
      'UNIQUE (region, area, brand, product, week_start)',
    ]),
    table('price_adjustments', [
      `id ${T.id}`,
      `week_start ${T.date} NOT NULL`,
      `week_end ${T.date} NULL`,
      `company ${T.str(60)} NOT NULL`,
      `product ${T.str(20)} NOT NULL`,
      `amount ${T.num} NOT NULL`,
      `source_url ${T.text} NULL`,
      `fetched_at ${T.ts} NOT NULL`,
      'UNIQUE (week_start, company, product)',
    ]),
    table('doe_documents', [
      `id ${T.id}`,
      `url_hash ${T.str(40)} NOT NULL UNIQUE`,
      `url ${T.text} NOT NULL`,
      `kind ${T.str(20)} NOT NULL`,
      `region ${T.str(40)} NULL`,
      `title ${T.str(255)} NULL`,
      `guessed_date ${T.date} NULL`,
      `week_start ${T.date} NULL`,
      `status ${T.str(20)} NOT NULL`,
      `message ${T.str(500)} NULL`,
      `rows_count ${T.int} NOT NULL DEFAULT 0`,
      `fetched_at ${T.ts} NOT NULL`,
    ]),
    table('stations', [
      `id ${T.id}`,
      `osm_id ${T.str(40)} NOT NULL UNIQUE`,
      `name ${T.str(160)} NULL`,
      `brand ${T.str(60)} NULL`,
      `lat ${T.num} NOT NULL`,
      `lng ${T.num} NOT NULL`,
      `address ${T.str(255)} NULL`,
      `opening_hours ${T.str(120)} NULL`,
      `updated_at ${T.ts} NOT NULL`,
    ]),
    table('community_prices', [
      `id ${T.id}`,
      `station_osm_id ${T.str(40)} NOT NULL`,
      `user_id ${T.int} NOT NULL`,
      `product ${T.str(20)} NOT NULL`,
      `price ${T.num} NOT NULL`,
      `note ${T.str(255)} NULL`,
      `reported_at ${T.ts} NOT NULL`,
    ]),
    table('news_articles', [
      `id ${T.id}`,
      `url_hash ${T.str(40)} NOT NULL UNIQUE`,
      `title_hash ${T.str(40)} NOT NULL`,
      `url ${T.text} NOT NULL`,
      `title ${T.str(400)} NOT NULL`,
      `source ${T.str(160)} NULL`,
      `summary ${T.text} NULL`,
      `categories ${T.str(160)} NULL`,
      `direction ${T.str(10)} NULL`,
      `provider ${T.str(30)} NOT NULL`,
      `published_at ${T.ts} NOT NULL`,
      `fetched_at ${T.ts} NOT NULL`,
    ]),
    table('market_series', [
      `id ${T.id}`,
      `series ${T.str(20)} NOT NULL`,
      `obs_date ${T.date} NOT NULL`,
      `value ${T.num} NOT NULL`,
      `source ${T.str(40)} NOT NULL`,
      'UNIQUE (series, obs_date)',
    ]),
    table('forecasts', [
      `id ${T.id}`,
      `target_week_start ${T.date} NOT NULL`,
      `product ${T.str(20)} NOT NULL`,
      `estimate ${T.num} NOT NULL`,
      `low ${T.num} NOT NULL`,
      `high ${T.num} NOT NULL`,
      `method ${T.str(60)} NOT NULL`,
      `details ${T.text} NULL`,
      `created_at ${T.ts} NOT NULL`,
      'UNIQUE (target_week_start, product)',
    ]),
    table('api_cache', [
      `cache_key ${T.str(40)} NOT NULL PRIMARY KEY`,
      `source ${T.str(40)} NOT NULL`,
      `payload ${T.big} NOT NULL`,
      `expires_at ${T.ts} NOT NULL`,
      `created_at ${T.ts} NOT NULL`,
    ]),
    table('integration_log', [
      `id ${T.id}`,
      `source ${T.str(40)} NOT NULL`,
      `endpoint ${T.str(255)} NOT NULL`,
      `status_code ${T.int} NULL`,
      `ok ${T.int} NOT NULL`,
      `duration_ms ${T.int} NOT NULL`,
      `error ${T.str(500)} NULL`,
      `created_at ${T.ts} NOT NULL`,
    ]),
    table('job_runs', [
      `id ${T.id}`,
      `job ${T.str(40)} NOT NULL`,
      `started_at ${T.ts} NOT NULL`,
      `finished_at ${T.ts} NULL`,
      `status ${T.str(20)} NOT NULL`,
      `items ${T.int} NOT NULL DEFAULT 0`,
      `message ${T.str(1000)} NULL`,
    ]),
    // kind: below | above (price threshold), adjustment (any new weekly adjustment), rollback (forecast)
    table('price_alerts', [
      `id ${T.id}`,
      `user_id ${T.int} NOT NULL`,
      `kind ${T.str(20)} NOT NULL`,
      `region ${T.str(40)} NOT NULL`,
      `product ${T.str(20)} NOT NULL`,
      `threshold ${T.num} NULL`,
      `active ${T.int} NOT NULL DEFAULT 1`,
      `last_triggered ${T.str(20)} NULL`,
      `created_at ${T.ts} NOT NULL`,
    ]),
    table('notifications', [
      `id ${T.id}`,
      `user_id ${T.int} NOT NULL`,
      `title ${T.str(200)} NOT NULL`,
      `body ${T.str(600)} NULL`,
      `link ${T.str(200)} NULL`,
      `created_at ${T.ts} NOT NULL`,
      `read_at ${T.ts} NULL`,
    ]),
    // Anonymous usage analytics for the admin dashboard: no coordinates or place names are stored.
    table('trip_logs', [
      `id ${T.id}`,
      `user_id ${T.int} NULL`,
      `vehicle_name ${T.str(120)} NULL`,
      `vehicle_category ${T.str(30)} NULL`,
      `fuel_type ${T.str(20)} NULL`,
      `product ${T.str(20)} NULL`,
      `region ${T.str(40)} NULL`,
      `distance_km ${T.num} NULL`,
      `liters ${T.num} NULL`,
      `cost ${T.num} NULL`,
      `round_trip ${T.int} NOT NULL DEFAULT 0`,
      `stops ${T.int} NOT NULL DEFAULT 0`,
      `created_at ${T.ts} NOT NULL`,
    ]),
    table('chat_logs', [
      `id ${T.id}`,
      `user_id ${T.int} NULL`,
      `message ${T.str(1000)} NOT NULL`,
      `intent ${T.str(40)} NULL`,
      `provider ${T.str(20)} NOT NULL`,
      `created_at ${T.ts} NOT NULL`,
    ]),
    index('idx_prices_lookup', 'fuel_prices', 'region, product, week_start'),
    index('idx_prices_area', 'fuel_prices', 'region, area, week_start'),
    index('idx_news_pub', 'news_articles', 'published_at'),
    index('idx_news_title', 'news_articles', 'title_hash'),
    index('idx_log_source', 'integration_log', 'source, created_at'),
    index('idx_jobs', 'job_runs', 'job, started_at'),
    index('idx_cprices', 'community_prices', 'station_osm_id, reported_at'),
    index('idx_logs_user', 'fuel_logs', 'user_id, filled_on'),
    index('idx_stations_geo', 'stations', 'lat, lng'),
    index('idx_notif_user', 'notifications', 'user_id, read_at'),
    index('idx_alerts_user', 'price_alerts', 'user_id'),
    index('idx_triplogs', 'trip_logs', 'created_at'),
    index('idx_chatlogs', 'chat_logs', 'created_at'),
  ];
}

/** Columns added after the first release: [probe query, ALTER statement]. Applied when the probe fails. */
export function columnMigrations(dialect) {
  const int = dialect === 'mysql' ? 'INT' : 'INTEGER';
  return [
    ['SELECT plate_digit FROM user_vehicles LIMIT 1', `ALTER TABLE user_vehicles ADD COLUMN plate_digit ${int} NULL`],
  ];
}
